    for col_idx, name in enumerate(COLUMNS, start=1):
        cell = ws.cell(row=1, column=col_idx, value=name)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = HEADER_ALIGN
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(col_idx)].width = COL_WIDTHS.get(name, 20)
    ws.row_dimensions[1].height = 36

    # Данные
    for row_idx, prod in enumerate(P, start=2):
        for col_idx, col_name in enumerate(COLUMNS, start=1):
            if col_name == "№":
                value = row_idx - 1
            elif col_name == "Сайт":
                value = prod.get("site", "")
            else:
                key = KEY_MAP.get(col_name)
                value = prod.get(key, "") if key else ""
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            cell.font = CELL_FONT
            cell.alignment = CELL_ALIGN
            cell.border = BORDER
            if row_idx % 2 == 0:
                cell.fill = BAND_FILL
            # Гиперссылка для сайта
            if col_name == "Сайт" and value.startswith("http"):
                cell.hyperlink = value
                cell.font = Font(name="Calibri", size=10, color="0066CC", underline="single")
